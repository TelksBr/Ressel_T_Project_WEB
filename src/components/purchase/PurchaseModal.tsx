interface PurchaseModalProps {
  plan: ResellerPlan;
  onClose: () => void;
}

const initialForm = (plan: ResellerPlan): PurchaseFormData => ({
  plan,
  resellerUsername: '',
  resellerEmail: '',
  resellerPassword: '',
  customerName: '',
  customerEmail: '',
  customerCpf: '',
  customerWhatsapp: '',
  paymentMethod: null,
  couponCode: '',
  cardNumber: '',
  cardholderName: '',
  cardExpMonth: '',
  cardExpYear: '',
  cardCvv: '',
  installments: 1,
});

type PaymentCategory = 'pix' | 'card' | 'wallet' | 'paypal' | 'ticket' | 'other';

function getCategory(method: PaymentMethod | null): PaymentCategory {
  if (!method) return 'pix';
  const id = (method.method_id || '').toLowerCase();
  const type = (method.type || '').toLowerCase();
  const provider = (
    method.gateway_provider ||
    method.gateway?.provider ||
    ''
  ).toLowerCase();

  if (id === 'pix' || type === 'pix' || type === 'instant') return 'pix';
  if (
    id === 'credit_card' ||
    id === 'card' ||
    type === 'card' ||
    type === 'credit_card'
  )
    return 'card';
  if (id === 'paypal' || provider === 'paypal') return 'paypal';
  if (id === 'account_money' || type === 'wallet') return 'wallet';
  if (
    [
      'oxxo',
      'paycash',
      'rapipago',
      'boleto',
      'cash',
      'ticket',
      'pagofacil',
    ].includes(id) ||
    type === 'cash' ||
    type === 'ticket'
  )
    return 'ticket';

  return 'other';
}

function getMethodIcon(category: PaymentCategory): ComponentType<{ className?: string }> {
  switch (category) {
    case 'pix':
      return QrCode;
    case 'card':
      return CreditCard;
    case 'wallet':
      return Wallet;
    case 'paypal':
      return ExternalLink;
    case 'ticket':
      return Receipt;
    default:
      return CreditCard;
  }
}

export function PurchaseModal({ plan, onClose }: PurchaseModalProps) {
  const steps: { key: PurchaseStep; label: string }[] = [
    { key: 'credentials', label: t('Conta') },
    { key: 'payment', label: t('Pagamento') },
    { key: 'checkout', label: t('Conclusão') },
    { key: 'success', label: t('Concluído') },
  ];

  const [step, setStep] = useState<PurchaseStep>('credentials');
  useBodyScrollLock(true);
  const [form, setForm] = useState<PurchaseFormData>(() => initialForm(plan));
  const [paymentMethods, setPaymentMethods] = useState<PaymentMethod[]>([]);
  const [loadingMethods, setLoadingMethods] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Random CPF state
  const [autoGeneratedCpf, setAutoGeneratedCpf] = useState(false);

  // Coupon state
  const [couponInput, setCouponInput] = useState('');
  const [validatingCoupon, setValidatingCoupon] = useState(false);
  const [appliedCoupon, setAppliedCoupon] =
    useState<CouponValidationData | null>(null);
  const [couponSuccess, setCouponSuccess] = useState(false);

  // Payment result & PayPal capture
  const [paymentResult, setPaymentResult] = useState<PaymentResult | null>(null);
  const [capturingPaypal, setCapturingPaypal] = useState(false);
  const [mpInstallments, setMpInstallments] = useState<MpInstallmentOption[]>([]);

  // Dynamic card installments & brand states
  const [loadingInstallments, setLoadingInstallments] = useState(false);
  const [installmentsFetched, setInstallmentsFetched] = useState(false);
  const [detectedBrand, setDetectedBrand] = useState<string | null>(null);
  const [detectedIssuerId, setDetectedIssuerId] = useState<string | null>(null);
  const [installmentsDropdownOpen, setInstallmentsDropdownOpen] = useState(false);
  const installmentsRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const handleClickOutside = (e: MouseEvent) => {
      if (
        installmentsRef.current &&
        !installmentsRef.current.contains(e.target as Node)
      ) {
        setInstallmentsDropdownOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const [usernameStatus, setUsernameStatus] = useState<
    'idle' | 'checking' | 'available' | 'taken'
  >('idle');
  const [emailStatus, setEmailStatus] = useState<
    'idle' | 'checking' | 'available' | 'taken'
  >('idle');
  const [copied, setCopied] = useState(false);

  const effectivePrice = appliedCoupon
    ? appliedCoupon.final_amount
    : plan.price;

  const currentCategory = getCategory(form.paymentMethod);

  // Normalização de parcelas (API backend ou Mercado Pago SDK) com juros
  const availableInstallmentOptions = useMemo(() => {
    if (
      form.paymentMethod?.installments &&
      form.paymentMethod.installments.length > 0
    ) {
      return form.paymentMethod.installments.map((inst) => {
        const count = inst.installments ?? inst.installment ?? 1;
        const installmentAmount =
          inst.installment_amount ?? inst.amount ?? effectivePrice / count;
        const totalAmount =
          inst.total_amount ?? inst.total ?? installmentAmount * count;
        const hasInterest =
          (inst.installment_rate != null && inst.installment_rate > 0) ||
          (inst.rate != null && inst.rate > 0) ||
          (totalAmount > effectivePrice + 0.05 && count > 1);

        return {
          count,
          installmentAmount,
          totalAmount,
          hasInterest,
          label:
            inst.recommended_message ??
            inst.message ??
            (count === 1
              ? t('1x à vista')
              : t('{count}x de {amount}', {
                  count,
                  amount: formatCurrency(installmentAmount),
                })),
        };
      });
    }

    if (mpInstallments.length > 0) {
      return mpInstallments.map((inst) => {
        const count = inst.installments;
        const installmentAmount = inst.installmentAmount;
        const totalAmount = inst.totalAmount;
        const hasInterest = Boolean(inst.hasInterest);

        return {
          count,
          installmentAmount,
          totalAmount,
          hasInterest,
          label:
            inst.recommendedMessage ||
            (count === 1
              ? t('1x à vista')
              : t('{count}x de {amount}', {
                  count,
                  amount: formatCurrency(installmentAmount),
                })),
        };
      });
    }

    return [];
  }, [form.paymentMethod, mpInstallments, effectivePrice]);

  const selectedOption = useMemo(() => {
    if (availableInstallmentOptions.length === 0) return null;
    return (
      availableInstallmentOptions.find(
        (o) => o.count === (form.installments || 1),
      ) || availableInstallmentOptions[0]
    );
  }, [availableInstallmentOptions, form.installments]);

  const updateForm = <K extends keyof PurchaseFormData>(
    key: K,
    value: PurchaseFormData[K],
  ) => {
    setForm((prev) => ({ ...prev, [key]: value }));
    setError(null);
  };

  const handleGenerateRandomCpf = () => {
    const validCpf = generateRandomCpf(true);
    updateForm('customerCpf', validCpf);
    setAutoGeneratedCpf(true);
    setError(null);
  };

  const checkUsername = useCallback(async (username: string) => {
    if (username.length < 3) {
      setUsernameStatus('idle');
      return;
    }
    setUsernameStatus('checking');
    try {
      const available = await veltrixApi.checkUsername(username);
      setUsernameStatus(available ? 'available' : 'taken');
    } catch (err) {
      const message = getErrorMessage(err, '');
      if (/já está em uso|already (in )?use|indisponível/i.test(message)) {
        setUsernameStatus('taken');
        setError(message);
      } else {
        setUsernameStatus('idle');
      }
    }
  }, []);

  const checkEmail = useCallback(async (email: string) => {
    if (!isValidEmail(email)) {
      setEmailStatus('idle');
      return;
    }
    setEmailStatus('checking');
    try {
      const available = await veltrixApi.checkEmail(email);
      setEmailStatus(available ? 'available' : 'taken');
    } catch (err) {
      const message = getErrorMessage(err, '');
      if (/já está em uso|already (in )?use|indisponível/i.test(message)) {
        setEmailStatus('taken');
        setError(message);
      } else {
        setEmailStatus('idle');
      }
    }
  }, []);

  useEffect(() => {
    const timer = setTimeout(() => checkUsername(form.resellerUsername), 500);
    return () => clearTimeout(timer);
  }, [form.resellerUsername, checkUsername]);

  useEffect(() => {
    const timer = setTimeout(() => checkEmail(form.resellerEmail), 500);
    return () => clearTimeout(timer);
  }, [form.resellerEmail, checkEmail]);

  // Load all payment methods configured in reseller panel
  useEffect(() => {
    if (step !== 'payment') return;

    setLoadingMethods(true);
    veltrixApi
      .getPaymentMethods(effectivePrice)
      .then((res) => {
        const methods = res.methods ?? [];
        setPaymentMethods(methods);

        setForm((prev) => {
          if (methods.length === 0) return { ...prev, paymentMethod: null };
          if (
            prev.paymentMethod &&
            methods.some(
              (m) =>
                m.gateway_id === prev.paymentMethod?.gateway_id &&
                m.method_id === prev.paymentMethod?.method_id,
            )
          ) {
            return prev;
          }
          return { ...prev, paymentMethod: methods[0] };
        });

        if (methods.length === 0) {
          setError(
            t('Nenhum método de pagamento disponível para este plano.'),
          );
        }
      })
      .catch((err) =>
        setError(
          getErrorMessage(
            err,
            t('Não foi possível carregar os métodos de pagamento.'),
          ),
        ),
      )
      .finally(() => setLoadingMethods(false));
  }, [step, effectivePrice]);

  // Consulta parcelas dinâmicas diretamente no Mercado Pago via BIN após validação
  useEffect(() => {
    if (step !== 'payment' || currentCategory !== 'card') {
      setMpInstallments([]);
      setInstallmentsFetched(false);
      setLoadingInstallments(false);
      setDetectedBrand(null);
      setDetectedIssuerId(null);
      setInstallmentsDropdownOpen(false);
      return;
    }

    const mpPublicKey = form.paymentMethod?.gateway?.mp_public_key;
    const cleanCard = (form.cardNumber || '').replace(/\D/g, '');
    const bin = cleanCard.slice(0, 6);

    if (!mpPublicKey || bin.length < 6) {
      setMpInstallments([]);
      setInstallmentsFetched(false);
      setLoadingInstallments(false);
      setDetectedBrand(null);
      setDetectedIssuerId(null);
      setInstallmentsDropdownOpen(false);
      setForm((prev) =>
        prev.installments !== 1 ? { ...prev, installments: 1 } : prev,
      );
      return;
    }

    let cancelled = false;
    setLoadingInstallments(true);
    setInstallmentsFetched(false);

    const timer = setTimeout(() => {
      getMpInstallments(mpPublicKey, effectivePrice, bin)
        .then((res) => {
          if (cancelled) return;
          const options = res?.options || [];
          setMpInstallments(options);
          setDetectedBrand(res?.paymentMethodId || null);
          setDetectedIssuerId(res?.issuerId || null);
          setInstallmentsFetched(true);

          setForm((prev) => {
            if (
              options.length > 0 &&
              !options.some((o) => o.installments === prev.installments)
            ) {
              return { ...prev, installments: 1 };
            }
            return prev;
          });
        })
        .catch((err) => {
          if (cancelled) return;
          console.warn('Falha ao obter parcelas:', err);
          setMpInstallments([]);
          setInstallmentsFetched(true);
        })
        .finally(() => {
          if (!cancelled) {
            setLoadingInstallments(false);
          }
        });
    }, 300);

    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [
    step,
    currentCategory,
    form.cardNumber,
    form.paymentMethod,
    effectivePrice,
  ]);

  // Auto-fill valid CPF if not yet provided so client is never blocked
  const goToPaymentStep = () => {
    if (!form.customerCpf) {
      const initialCpf = generateRandomCpf(true);
      updateForm('customerCpf', initialCpf);
      setAutoGeneratedCpf(true);
    }
    setStep('payment');
  };

  const {
    status: paymentStatus,
    provisioning,
    credentials,
    error: pollingError,
  } = usePaymentPolling({
    paymentId: paymentResult?.payment_id ?? null,
    enabled:
      (step === 'checkout' || step === 'pix') &&
      Boolean(paymentResult?.payment_id),
    onApproved: () => setStep('success'),
    onRejected: (msg) => setError(msg ?? t('Pagamento recusado ou cancelado.')),
  });

  const validateCredentials = (): boolean => {
    if (!/^[a-zA-Z0-9]{3,32}$/.test(form.resellerUsername)) {
      setError(
        t('Username deve ter 3 a 32 caracteres, apenas letras e números.'),
      );
      return false;
    }
    if (usernameStatus === 'checking' || emailStatus === 'checking') {
      setError(t('Aguarde a verificação do username e e-mail.'));
      return false;
    }
    if (usernameStatus === 'taken') {
      setError(t('Este username já está em uso.'));
      return false;
    }
    if (!isValidEmail(form.resellerEmail)) {
      setError(t('Informe um e-mail válido para a conta de revenda.'));
      return false;
    }
    if (emailStatus === 'taken') {
      setError(t('Este e-mail já está em uso.'));
      return false;
    }
    if (form.resellerPassword.length < 6) {
      setError(t('A senha deve ter pelo menos 6 caracteres.'));
      return false;
    }
    return true;
  };

  const isCpfRequiredForMethod = (): boolean => {
    if (!form.paymentMethod) return true;
    const cat = getCategory(form.paymentMethod);
    if (cat === 'paypal') return false;

    const rules = form.paymentMethod.gateway?.payer_document_rules;
    if (rules && Object.keys(rules).length > 0) {
      const methodId = form.paymentMethod.method_id || form.paymentMethod.type;
      return Boolean(rules[methodId] || rules[form.paymentMethod.type]);
    }
    return true;
  };

  const validatePayment = (): boolean => {
    if (!form.customerName.trim()) {
      setError(t('Informe seu nome completo.'));
      return false;
    }
    if (!isValidEmail(form.customerEmail)) {
      setError(t('Informe um e-mail válido.'));
      return false;
    }

    if (isCpfRequiredForMethod()) {
      if (!form.customerCpf || !isValidCpf(form.customerCpf)) {
        // Auto-generate a valid CPF on the fly if invalid/empty so user isn't stuck
        const freshCpf = generateRandomCpf(true);
        updateForm('customerCpf', freshCpf);
        setAutoGeneratedCpf(true);
      }
    }

    if (!form.paymentMethod) {
      setError(t('Selecione um método de pagamento.'));
      return false;
    }

    if (currentCategory === 'card') {
      const cleanCard = (form.cardNumber || '').replace(/\D/g, '');
      if (cleanCard.length < 13 || cleanCard.length > 19) {
        setError(t('Número do cartão inválido.'));
        return false;
      }
      if (loadingInstallments) {
        setError(t('Aguarde a verificação das parcelas disponíveis.'));
        return false;
      }
      if (!form.cardholderName?.trim()) {
        setError(t('Informe o nome impresso no cartão.'));
        return false;
      }
      const expMonth = Number(form.cardExpMonth || 0);
      const expYear = Number(form.cardExpYear || 0);
      if (expMonth < 1 || expMonth > 12 || !expYear) {
        setError(t('Informe o mês e ano de validade do cartão.'));
        return false;
      }
      const cleanCvv = (form.cardCvv || '').replace(/\D/g, '');
      if (cleanCvv.length < 3 || cleanCvv.length > 4) {
        setError(t('Código de segurança (CVV) inválido.'));
        return false;
      }
    }

    return true;
  };

  const handleApplyCoupon = async () => {
    if (!couponInput.trim()) {
      setError(t('Código do cupom é obrigatório.'));
      return;
    }

    setValidatingCoupon(true);
    setError(null);
    try {
      const res = await veltrixApi.validateCoupon(
        couponInput.trim(),
        plan.id,
        plan.price,
      );
      if (res.success && res.data) {
        setAppliedCoupon(res.data);
        updateForm('couponCode', res.data.code);
        updateForm('installments', 1);
        setCouponSuccess(true);
        setTimeout(() => setCouponSuccess(false), 3000);
      } else {
        setError(res.message || t('Erro ao validar cupom.'));
      }
    } catch (err) {
      setError(getErrorMessage(err, t('Erro ao validar cupom.')));
    } finally {
      setValidatingCoupon(false);
    }
  };

  const handleRemoveCoupon = () => {
    setAppliedCoupon(null);
    setCouponInput('');
    updateForm('couponCode', '');
    updateForm('installments', 1);
  };

  const handleCreatePayment = async () => {
    if (!form.paymentMethod) return;

    setSubmitting(true);
    setError(null);

    try {
      let cardToken: string | undefined;
      let mpPaymentMethodId: string | undefined;

      const mpPublicKey = form.paymentMethod.gateway?.mp_public_key;

      if (currentCategory === 'card' && mpPublicKey) {
        try {
          const tokenRes = await createMpCardToken({
            publicKey: mpPublicKey,
            cardNumber: form.cardNumber || '',
            cardholderName: form.cardholderName || form.customerName,
            cardExpirationMonth: form.cardExpMonth || '',
            cardExpirationYear: form.cardExpYear || '',
            securityCode: form.cardCvv || '',
            identificationType:
              form.paymentMethod.gateway?.payer_document?.type || 'CPF',
            identificationNumber: stripDigits(form.customerCpf),
          });
          cardToken = tokenRes.token;
          mpPaymentMethodId = tokenRes.paymentMethodId;
        } catch (cardErr) {
          setError(
            getErrorMessage(cardErr, t('Erro ao processar pagamento.')),
          );
          setSubmitting(false);
          return;
        }
      }

      const methodId =
        form.paymentMethod.method_id || form.paymentMethod.type;

      const result = await veltrixApi.createPayment({
        plan_id: plan.id,
        gateway_id: form.paymentMethod.gateway_id,
        payment_method_type: methodId,
        customer_name: form.customerName.trim(),
        customer_email: form.customerEmail.trim(),
        customer_cpf: isCpfRequiredForMethod()
          ? stripDigits(form.customerCpf)
          : undefined,
        customer_whatsapp: stripDigits(form.customerWhatsapp) || undefined,
        identification_type:
          form.paymentMethod.gateway?.payer_document?.type || 'CPF',
        reseller_username: form.resellerUsername.trim(),
        reseller_email: form.resellerEmail.trim(),
        reseller_password: form.resellerPassword,
        card_token: cardToken,
        mp_payment_method_id: mpPaymentMethodId || detectedBrand || undefined,
        installments: form.installments || 1,
        issuer_id: detectedIssuerId || undefined,
        cardholder_name: form.cardholderName?.trim() || form.customerName.trim(),
        mp_public_key_used: mpPublicKey,
        return_url:
          typeof window !== 'undefined' ? window.location.href : undefined,
        coupon_code: appliedCoupon?.code,
      });

      if (!result.payment_id) {
        throw new Error(t('Pagamento criado, mas ID não retornado pela API.'));
      }

      setPaymentResult(result);

      if (result.status === 'approved') {
        setStep('success');
      } else {
        setStep('checkout');
      }
    } catch (err) {
      setError(getErrorMessage(err, t('Erro ao processar pagamento.')));
    } finally {
      setSubmitting(false);
    }
  };

  const handleCapturePaypal = async () => {
    if (!paymentResult?.payment_id) return;
    setCapturingPaypal(true);
    setError(null);
    try {
      const res = await veltrixApi.capturePaypal(
        paymentResult.payment_id,
        paymentResult.paypal?.order_id,
      );
      if (res.status === 'approved') {
        setStep('success');
      } else {
        setError(t('Pagamento em processamento'));
      }
    } catch (err) {
      setError(
        getErrorMessage(err, t('Falha ao capturar pagamento no PayPal.')),
      );
    } finally {
      setCapturingPaypal(false);
    }
  };

  const copyPixCode = async () => {
    const textToCopy =
      paymentResult?.pix?.qr_code_text ||
      paymentResult?.pix_copy_paste ||
      paymentResult?.copy_paste ||
      paymentResult?.emv;
    if (!textToCopy) return;
    await navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const copyBarcode = async () => {
    const code = paymentResult?.ticket?.barcode;
    if (!code) return;
    await navigator.clipboard.writeText(code);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const currentStepIndex =
    step === 'pix' ? 2 : steps.findIndex((s) => s.key === step);

  useEffect(() => {
    const handleEscape = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        if (step === 'checkout' || step === 'pix') return;
        onClose();
      }
    };
    window.addEventListener('keydown', handleEscape);
    return () => window.removeEventListener('keydown', handleEscape);
  }, [step, onClose]);

  const handleBackdropClick = () => {
    if (step === 'checkout' || step === 'pix') return;
    onClose();
  };

  const getSubmitButtonLabel = () => {
    switch (currentCategory) {
      case 'pix':
        return t('Pagar com PIX');
      case 'card':
        return t('Pagar com Cartão');
      case 'wallet':
        return t('Pagar com Mercado Pago');
      case 'paypal':
        return t('Pagar com PayPal');
      case 'ticket':
        return t('Gerar Boleto / Ticket');
      default:
        return t('Finalizar Pagamento');
    }
  };

  return (
    <div className="fixed inset-0 z-[100] flex items-end justify-center sm:items-center sm:p-4">
      <div
        className="absolute inset-0 bg-black/70 backdrop-blur-sm"
        onClick={handleBackdropClick}
      />

      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby="purchase-modal-title"
        className="relative flex max-h-[92dvh] w-full max-w-2xl flex-col overflow-hidden rounded-t-2xl border border-white/10 bg-surface-raised shadow-2xl sm:max-h-[95vh] sm:rounded-3xl pb-[env(safe-area-inset-bottom)]"
      >
        {/* Header */}
        <div className="flex items-start justify-between gap-3 border-b border-white/[0.06] px-4 py-3.5 sm:px-6 sm:py-4">
          <div className="min-w-0 flex-1">
            <p className="text-[10px] font-semibold uppercase tracking-widest text-brand-400 sm:text-xs">
              {t('Comprar Plano')}
            </p>
            <h3
              id="purchase-modal-title"
              className="truncate font-display text-base font-bold text-white sm:text-lg"
            >
              {plan.name}
            </h3>
            <div className="flex items-center gap-2">
              <p className="text-sm font-semibold text-gray-300">
                {formatCurrency(effectivePrice)}
              </p>
              {appliedCoupon && (
                <span className="text-xs text-gray-500 line-through">
                  {formatCurrency(plan.price)}
                </span>
              )}
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-2 text-gray-400 transition hover:bg-white/5 hover:text-white"
            aria-label={t('Fechar')}
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Step indicator */}
        {step !== 'success' && (
          <>
            <p className="border-b border-white/[0.06] px-4 py-2 text-center text-[11px] text-gray-500 sm:hidden">
              {t('Passo')} {currentStepIndex + 1} {t('de 3 —')}{' '}
              {steps[currentStepIndex]?.label}
            </p>
            <div className="flex items-center gap-1 border-b border-white/[0.06] px-3 py-2.5 sm:gap-2 sm:px-6 sm:py-3">
              {steps.slice(0, 3).map((s, i) => (
                <div
                  key={s.key}
                  className="flex flex-1 items-center gap-1 sm:gap-2"
                >
                  <div
                    className={`flex h-6 w-6 shrink-0 items-center justify-center rounded-full text-[10px] font-bold transition sm:h-7 sm:w-7 sm:text-xs ${
                      i < currentStepIndex
                        ? 'bg-brand-500 text-white'
                        : i === currentStepIndex
                          ? 'border border-brand-400 bg-brand-500/20 text-brand-300'
                          : 'border border-white/10 text-gray-500'
                    }`}
                  >
                    {i < currentStepIndex ? (
                      <Check className="h-3.5 w-3.5" />
                    ) : (
                      i + 1
                    )}
                  </div>
                  <span
                    className={`hidden text-xs sm:block ${i === currentStepIndex ? 'text-white' : 'text-gray-500'}`}
                  >
                    {s.label}
                  </span>
                  {i < 2 && <div className="mx-1 h-px flex-1 bg-white/10" />}
                </div>
              ))}
            </div>
          </>
        )}

        {error && (
          <div className="border-b border-red-500/20 bg-red-500/10 px-4 py-3 text-sm text-red-300 sm:px-6">
            {t(error)}
          </div>
        )}

        {/* Content */}
        <div className="flex-1 overflow-y-auto overscroll-contain px-4 py-5 sm:px-6 sm:py-6">
          {/* Step 1: Credentials */}
          {step === 'credentials' && (
            <div className="space-y-5">
              <div>
                <h4 className="font-display text-xl font-bold text-white">
                  {t('Credenciais do Painel')}
                </h4>
                <p className="mt-1 text-sm text-gray-400">
                  {t(
                    'Defina o usuário e senha que você usará para acessar o painel de revenda.',
                  )}
                </p>
              </div>

              <div className="space-y-4">
                <Field label={t('Username')} icon={User}>
                  <input
                    type="text"
                    value={form.resellerUsername}
                    onChange={(e) =>
                      updateForm(
                        'resellerUsername',
                        e.target.value
                          .replace(/[^a-zA-Z0-9]/g, '')
                          .slice(0, 32),
                      )
                    }
                    placeholder={t('seurevenda')}
                    className="input-field"
                    autoComplete="username"
                  />
                  <AvailabilityHint status={usernameStatus} />
                </Field>

                <Field label={t('E-mail da conta')} icon={Mail}>
                  <input
                    type="email"
                    value={form.resellerEmail}
                    onChange={(e) =>
                      updateForm('resellerEmail', e.target.value)
                    }
                    placeholder={t('revenda@email.com')}
                    className="input-field"
                    autoComplete="email"
                  />
                  <AvailabilityHint status={emailStatus} />
                </Field>

                <Field label={t('Senha')} icon={Lock}>
                  <input
                    type="password"
                    value={form.resellerPassword}
                    onChange={(e) =>
                      updateForm('resellerPassword', e.target.value)
                    }
                    placeholder={t('Mínimo 6 caracteres')}
                    className="input-field"
                    autoComplete="new-password"
                  />
                </Field>
              </div>

              <div className="rounded-xl border border-brand-500/20 bg-brand-500/5 p-4">
                <p className="text-xs text-gray-400">
                  {t(
                    'Após a confirmação do pagamento, suas credenciais serão exibidas aqui e enviadas para o e-mail informado.',
                  )}
                </p>
              </div>
            </div>
          )}

          {/* Step 2: Payment */}
          {step === 'payment' && (
            <div className="space-y-5">
              <div>
                <h4 className="font-display text-xl font-bold text-white">
                  {t('Dados de Pagamento')}
                </h4>
                <p className="mt-1 text-sm text-gray-400">
                  {t('Informe seus dados para concluir o pagamento.')}
                </p>
              </div>

              {/* Plano e Cupom de Desconto no Topo: aplicado antes das parcelas */}
              <div className="rounded-2xl border border-white/[0.08] bg-white/[0.03] p-4 sm:p-5">
                <div className="flex items-center justify-between border-b border-white/[0.06] pb-3">
                  <div>
                    <span className="text-xs uppercase tracking-wider text-gray-400">
                      {t('Plano selecionado')}
                    </span>
                    <h5 className="font-display text-base font-bold text-white sm:text-lg">
                      {plan.name}
                    </h5>
                  </div>
                  <div className="text-right">
                    <span className="font-display text-xl font-bold text-white">
                      {formatCurrency(effectivePrice)}
                    </span>
                    {appliedCoupon && (
                      <span className="block text-xs text-gray-400 line-through">
                        {formatCurrency(plan.price)}
                      </span>
                    )}
                  </div>
                </div>

                <div className="mt-3.5">
                  <div className="flex items-center gap-1.5 text-xs font-semibold text-gray-300">
                    <Tag className="h-3.5 w-3.5 text-brand-400" />
                    <span>{t('Cupom de desconto')}</span>
                  </div>

                  {appliedCoupon ? (
                    <div className="mt-2 flex items-center justify-between rounded-xl border border-green-500/30 bg-green-500/10 px-3.5 py-2 text-sm text-green-300">
                      <div className="flex items-center gap-2">
                        <Check className="h-4 w-4 text-green-400" />
                        <span className="font-mono font-bold">
                          {appliedCoupon.code}
                        </span>
                        <span className="text-xs text-green-400/90">
                          (-{formatCurrency(appliedCoupon.discount_amount)})
                        </span>
                      </div>
                      <button
                        type="button"
                        onClick={handleRemoveCoupon}
                        className="text-xs font-medium text-red-400 hover:underline"
                      >
                        {t('Remover')}
                      </button>
                    </div>
                  ) : (
                    <div className="mt-2 flex gap-2">
                      <input
                        type="text"
                        value={couponInput}
                        onChange={(e) =>
                          setCouponInput(e.target.value.toUpperCase())
                        }
                        placeholder="PROMO10"
                        className="input-field flex-1 py-2.5 uppercase"
                      />
                      <button
                        type="button"
                        onClick={handleApplyCoupon}
                        disabled={validatingCoupon || !couponInput.trim()}
                        className="btn-secondary px-4 py-2.5 text-xs font-semibold disabled:opacity-50"
                      >
                        {validatingCoupon ? (
                          <Loader2 className="h-3.5 w-3.5 animate-spin" />
                        ) : (
                          t('Aplicar')
                        )}
                      </button>
                    </div>
                  )}

                  {couponSuccess && (
                    <p className="mt-1.5 text-xs text-green-400">
                      {t('Cupom aplicado!')}
                    </p>
                  )}
                </div>
              </div>

              <div className="space-y-4">
                <Field label={t('Nome completo')} icon={User}>
                  <input
                    type="text"
                    value={form.customerName}
                    onChange={(e) => updateForm('customerName', e.target.value)}
                    placeholder={t('João Silva')}
                    className="input-field"
                  />
                </Field>

                <Field label={t('E-mail')} icon={Mail}>
                  <input
                    type="email"
                    value={form.customerEmail}
                    onChange={(e) =>
                      updateForm('customerEmail', e.target.value)
                    }
                    placeholder={t('seu@email.com')}
                    className="input-field"
                  />
                </Field>

                {/* CPF Field with Random CPF Generator */}
                {isCpfRequiredForMethod() && (
                  <div>
                    <div className="mb-1.5 flex items-center justify-between">
                      <label className="flex items-center gap-1.5 text-sm font-medium text-gray-300">
                        <Shield className="h-3.5 w-3.5 text-brand-400" />
                        {t('CPF')}
                      </label>
                      <button
                        type="button"
                        onClick={handleGenerateRandomCpf}
                        className="flex items-center gap-1 rounded-md border border-brand-500/30 bg-brand-500/10 px-2.5 py-1 text-xs font-medium text-brand-300 transition hover:bg-brand-500/20 hover:text-white"
                      >
                        <Sparkles className="h-3 w-3 text-brand-400" />
                        {autoGeneratedCpf
                          ? t('Gerar novo CPF')
                          : t('Gerar CPF')}
                      </button>
                    </div>
                    <input
                      type="text"
                      value={form.customerCpf}
                      onChange={(e) => {
                        updateForm('customerCpf', formatCpf(e.target.value));
                        setAutoGeneratedCpf(false);
                      }}
                      placeholder="000.000.000-00"
                      className="input-field"
                      maxLength={14}
                    />
                    {autoGeneratedCpf && (
                      <p className="mt-1.5 flex items-center gap-1 text-xs text-brand-400">
                        <Sparkles className="h-3 w-3 shrink-0" />
                        {t(
                          'CPF aleatório gerado (válido). Seu CPF real não é exigido.',
                        )}
                      </p>
                    )}
                  </div>
                )}

                <Field label={t('WhatsApp (opcional)')} icon={User}>
                  <input
                    type="text"
                    value={form.customerWhatsapp}
                    onChange={(e) =>
                      updateForm(
                        'customerWhatsapp',
                        formatPhone(e.target.value),
                      )
                    }
                    placeholder="+55 (13) 99999-9999"
                    className="input-field"
                  />
                </Field>
              </div>

              {/* Payment Methods Selection */}
              <div>
                <p className="mb-3 text-sm font-semibold text-white">
                  {t('Método de pagamento')}
                </p>
                {loadingMethods ? (
                  <div className="flex items-center justify-center py-8 text-gray-400">
                    <Loader2 className="mr-2 h-5 w-5 animate-spin" />
                    {t('Carregando...')}
                  </div>
                ) : paymentMethods.length === 0 ? (
                  <p className="text-sm text-gray-500">
                    {t('Nenhum método de pagamento disponível.')}
                  </p>
                ) : (
                  <div className="grid gap-2">
                    {paymentMethods.map((method) => {
                      const cat = getCategory(method);
                      const Icon = getMethodIcon(cat);
                      const isSelected =
                        form.paymentMethod?.gateway_id === method.gateway_id &&
                        form.paymentMethod?.method_id === method.method_id;

                      return (
                        <button
                          key={`${method.gateway_id}-${method.method_id || method.type}`}
                          type="button"
                          onClick={() => updateForm('paymentMethod', method)}
                          className={`flex items-center justify-between rounded-xl border p-4 text-left transition ${
                            isSelected
                              ? 'border-brand-500/50 bg-brand-500/10'
                              : 'border-white/[0.08] bg-white/[0.02] hover:border-white/15'
                          }`}
                        >
                          <div className="flex items-center gap-3">
                            <div
                              className={`flex h-10 w-10 items-center justify-center rounded-lg border ${
                                isSelected
                                  ? 'border-brand-500/30 bg-brand-500/20 text-brand-300'
                                  : 'border-white/10 bg-white/5 text-gray-400'
                              }`}
                            >
                              <Icon className="h-5 w-5" />
                            </div>
                            <div>
                              <span className="block font-medium text-white">
                                {method.name ||
                                  paymentMethodLabel(
                                    method.type,
                                    method.name,
                                  )}
                              </span>
                              {method.description && (
                                <span className="block text-xs text-gray-400">
                                  {method.description}
                                </span>
                              )}
                            </div>
                          </div>
                          {isSelected && (
                            <CheckCircle2 className="h-5 w-5 shrink-0 text-brand-400" />
                          )}
                        </button>
                      );
                    })}
                  </div>
                )}
              </div>

              {/* Credit Card Details (when card is selected) */}
              {currentCategory === 'card' && (
                <div className="space-y-4 rounded-2xl border border-white/10 bg-white/[0.02] p-4 sm:p-5">
                  <div className="flex items-center gap-2 border-b border-white/[0.06] pb-3">
                    <CreditCard className="h-4 w-4 text-brand-400" />
                    <h5 className="font-semibold text-white">
                      {t('Dados do Cartão')}
                    </h5>
                  </div>

                  <Field label={t('Número do Cartão')} icon={CreditCard}>
                    <div className="relative">
                      <input
                        type="text"
                        value={form.cardNumber || ''}
                        onChange={(e) =>
                          updateForm(
                            'cardNumber',
                            formatCardNumber(e.target.value),
                          )
                        }
                        placeholder="0000 0000 0000 0000"
                        className="input-field pr-20"
                        maxLength={23}
                      />
                      {detectedBrand && (
                        <div className="pointer-events-none absolute inset-y-0 right-3 flex items-center">
                          <span className="rounded-md border border-brand-500/30 bg-brand-500/20 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider text-brand-300">
                            {detectedBrand}
                          </span>
                        </div>
                      )}
                    </div>
                  </Field>

                  <Field label={t('Nome impresso no cartão')} icon={User}>
                    <input
                      type="text"
                      value={form.cardholderName || ''}
                      onChange={(e) =>
                        updateForm('cardholderName', e.target.value.toUpperCase())
                      }
                      placeholder={form.customerName || t('João Silva')}
                      className="input-field uppercase"
                    />
                  </Field>

                  <div className="grid grid-cols-2 gap-3">
                    <Field label={t('Validade')} icon={CreditCard}>
                      <input
                        type="text"
                        value={
                          form.cardExpMonth && form.cardExpYear
                            ? `${form.cardExpMonth}/${form.cardExpYear}`
                            : form.cardExpMonth || ''
                        }
                        onChange={(e) => {
                          const formatted = formatCardExpiry(e.target.value);
                          const [m, y] = formatted.split('/');
                          updateForm('cardExpMonth', m || '');
                          updateForm('cardExpYear', y || '');
                        }}
                        placeholder="MM/AA"
                        className="input-field"
                        maxLength={5}
                      />
                    </Field>

                    <Field label={t('CVV')} icon={Lock}>
                      <input
                        type="text"
                        value={form.cardCvv || ''}
                        onChange={(e) =>
                          updateForm(
                            'cardCvv',
                            e.target.value.replace(/\D/g, '').slice(0, 4),
                          )
                        }
                        placeholder="123"
                        className="input-field"
                        maxLength={4}
                      />
                    </Field>
                  </div>

                  {/* Parcelas com exibição condicional: somente após validar cartão e obter opções */}
                  {(() => {
                    const cleanCard = (form.cardNumber || '').replace(/\D/g, '');
                    const hasMinCardDigits = cleanCard.length >= 6;

                    if (!hasMinCardDigits) {
                      return (
                        <div className="flex items-center gap-3 rounded-xl border border-white/[0.08] bg-white/[0.02] p-3.5 text-xs text-gray-400">
                          <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg border border-white/10 bg-white/5 text-brand-400">
                            <CreditCard className="h-4 w-4" />
                          </div>
                          <div>
                            <p className="font-medium text-gray-300">
                              {t('Opções de parcelamento')}
                            </p>
                            <p className="text-gray-500">
                              {t(
                                'Informe o número do cartão para ver as parcelas disponíveis.',
                              )}
                            </p>
                          </div>
                        </div>
                      );
                    }

                    if (loadingInstallments) {
                      return (
                        <div className="flex items-center gap-3 rounded-xl border border-brand-500/30 bg-brand-500/10 p-3.5 text-xs text-brand-300">
                          <Loader2 className="h-4 w-4 shrink-0 animate-spin text-brand-400" />
                          <div>
                            <p className="font-medium text-white">
                              {t('Consultando parcelas disponíveis...')}
                            </p>
                            <p className="text-brand-300/80">
                              {t(
                                'Verificando juros e condições com a operadora...',
                              )}
                            </p>
                          </div>
                        </div>
                      );
                    }

                    if (
                      installmentsFetched &&
                      availableInstallmentOptions.length === 0
                    ) {
                      return (
                        <div className="rounded-xl border border-amber-500/20 bg-amber-500/10 p-3 text-xs text-amber-300">
                          {t(
                            'Nenhuma opção de parcelamento encontrada para este cartão.',
                          )}
                        </div>
                      );
                    }

                    if (
                      installmentsFetched &&
                      availableInstallmentOptions.length > 0
                    ) {
                      return (
                        <div className="relative" ref={installmentsRef}>
                          <div className="mb-1.5 flex items-center justify-between text-sm font-medium text-gray-300">
                            <span className="flex items-center gap-1.5">
                              <CreditCard className="h-3.5 w-3.5 text-brand-400" />
                              {t('Parcelas')}
                            </span>
                            {selectedOption &&
                              !selectedOption.hasInterest &&
                              selectedOption.count > 1 && (
                                <span className="rounded-md bg-emerald-500/20 px-2 py-0.5 text-[11px] font-semibold text-emerald-300">
                                  {t('Sem juros')}
                                </span>
                              )}
                          </div>

                          {/* Trigger Custom Dropdown */}
                          <button
                            type="button"
                            onClick={() =>
                              setInstallmentsDropdownOpen((prev) => !prev)
                            }
                            className="input-field flex w-full items-center justify-between gap-3 text-left transition hover:border-brand-500/40"
                          >
                            <div className="flex flex-1 items-center justify-between gap-2">
                              <span className="font-medium text-white">
                                {selectedOption
                                  ? selectedOption.count === 1
                                    ? t('1x à vista')
                                    : t('{count}x de {amount}', {
                                        count: selectedOption.count,
                                        amount: formatCurrency(
                                          selectedOption.installmentAmount,
                                        ),
                                      })
                                  : t('1x à vista')}
                              </span>
                              <div className="flex items-center gap-2">
                                {selectedOption && (
                                  <span
                                    className={`rounded-md px-2 py-0.5 text-[11px] font-semibold ${
                                      selectedOption.hasInterest
                                        ? 'bg-white/10 text-gray-300'
                                        : 'bg-emerald-500/15 text-emerald-300'
                                    }`}
                                  >
                                    {selectedOption.hasInterest
                                      ? t('Com juros')
                                      : t('Sem juros')}
                                  </span>
                                )}
                                {selectedOption && selectedOption.count > 1 && (
                                  <span className="text-xs text-gray-400">
                                    {t('Total: {total}', {
                                      total: formatCurrency(
                                        selectedOption.totalAmount,
                                      ),
                                    })}
                                  </span>
                                )}
                              </div>
                            </div>
                            <ChevronDown
                              className={`h-4 w-4 shrink-0 text-gray-400 transition-transform duration-200 ${
                                installmentsDropdownOpen ? 'rotate-180' : ''
                              }`}
                            />
                          </button>

                          {/* Floating Options Menu */}
                          {installmentsDropdownOpen && (
                            <div className="absolute left-0 right-0 top-full z-50 mt-1.5 max-h-60 overflow-y-auto rounded-xl border border-white/15 bg-[#12101c] p-1.5 shadow-2xl backdrop-blur-xl">
                              {availableInstallmentOptions.map((opt) => {
                                const isSelected =
                                  (form.installments || 1) === opt.count;
                                return (
                                  <button
                                    key={opt.count}
                                    type="button"
                                    onClick={() => {
                                      updateForm('installments', opt.count);
                                      setInstallmentsDropdownOpen(false);
                                    }}
                                    className={`flex w-full items-center justify-between rounded-lg px-3.5 py-2.5 text-left text-sm transition ${
                                      isSelected
                                        ? 'border border-brand-500/40 bg-brand-500/20 font-medium text-white'
                                        : 'text-gray-200 hover:bg-white/[0.06] hover:text-white'
                                    }`}
                                  >
                                    <div className="flex items-center gap-2.5">
                                      <div
                                        className={`flex h-6 w-6 shrink-0 items-center justify-center rounded-full border text-xs ${
                                          isSelected
                                            ? 'border-brand-400 bg-brand-500 text-white'
                                            : 'border-white/20 text-gray-400'
                                        }`}
                                      >
                                        {isSelected ? (
                                          <Check className="h-3.5 w-3.5" />
                                        ) : (
                                          `${opt.count}x`
                                        )}
                                      </div>
                                      <div>
                                        <span className="block font-medium text-white">
                                          {opt.count === 1
                                            ? t('1x à vista')
                                            : t('{count}x de {amount}', {
                                                count: opt.count,
                                                amount: formatCurrency(
                                                  opt.installmentAmount,
                                                ),
                                              })}
                                        </span>
                                        {opt.count > 1 && (
                                          <span className="block text-xs text-gray-400">
                                            {t('Total: {total}', {
                                              total: formatCurrency(
                                                opt.totalAmount,
                                              ),
                                            })}
                                          </span>
                                        )}
                                      </div>
                                    </div>

                                    <div className="flex items-center gap-2">
                                      <span
                                        className={`rounded-md px-2 py-0.5 text-[11px] font-semibold ${
                                          opt.hasInterest
                                            ? 'bg-white/10 text-gray-400'
                                            : 'bg-emerald-500/15 text-emerald-300'
                                        }`}
                                      >
                                        {opt.hasInterest
                                          ? t('Com juros')
                                          : t('Sem juros')}
                                      </span>
                                      {isSelected && (
                                        <CheckCircle2 className="h-4 w-4 shrink-0 text-brand-400" />
                                      )}
                                    </div>
                                  </button>
                                );
                              })}
                            </div>
                          )}
                        </div>
                      );
                    }

                    return null;
                  })()}
                </div>
              )}

              {/* Summary Card */}
              <div className="rounded-xl border border-white/[0.08] bg-white/[0.03] p-4">
                <div className="flex justify-between text-sm">
                  <span className="text-gray-400">
                    {t('Plano selecionado')}
                  </span>
                  <span className="font-semibold text-white">{plan.name}</span>
                </div>
                {appliedCoupon && (
                  <div className="mt-1 flex justify-between text-sm text-green-400">
                    <span>{t('Desconto')}</span>
                    <span>
                      -{formatCurrency(appliedCoupon.discount_amount)}
                    </span>
                  </div>
                )}
                <div className="mt-2 flex justify-between border-t border-white/[0.06] pt-2">
                  <span className="text-gray-400">{t('Total')}</span>
                  <div className="text-right">
                    <span className="font-display text-xl font-bold text-white">
                      {formatCurrency(
                        currentCategory === 'card' && selectedOption
                          ? selectedOption.totalAmount
                          : effectivePrice,
                      )}
                    </span>
                    {currentCategory === 'card' &&
                      selectedOption &&
                      selectedOption.count > 1 && (
                        <span className="block text-xs text-gray-400">
                          {t('{count}x de {amount}', {
                            count: selectedOption.count,
                            amount: formatCurrency(
                              selectedOption.installmentAmount,
                            ),
                          })}
                        </span>
                      )}
                  </div>
                </div>
              </div>
            </div>
          )}

          {/* Step 3: Checkout / Payment Status */}
          {(step === 'checkout' || step === 'pix') && (
            <div className="space-y-5 text-center">
              {/* PIX Flow */}
              {currentCategory === 'pix' && (
                <>
                  <div>
                    <div className="mx-auto mb-4 flex h-14 w-14 items-center justify-center rounded-2xl border border-brand-500/30 bg-brand-500/10">
                      <QrCode className="h-7 w-7 text-brand-300" />
                    </div>
                    <h4 className="font-display text-xl font-bold text-white">
                      {t('Pague via PIX')}
                    </h4>
                    <p className="mt-1 text-sm text-gray-400">
                      {t(
                        'Escaneie o QR Code ou copie o código abaixo. A confirmação é automática.',
                      )}
                    </p>
                  </div>

                  {paymentResult?.pix_qr_code_base64 ||
                  paymentResult?.pix?.qr_code_base64 ? (
                    <div className="mx-auto w-fit rounded-2xl border border-white/10 bg-white p-4">
                      <img
                        src={
                          paymentResult.pix_qr_code_base64?.startsWith('data:')
                            ? paymentResult.pix_qr_code_base64
                            : `data:image/png;base64,${paymentResult.pix_qr_code_base64 || paymentResult.pix?.qr_code_base64}`
                        }
                        alt={t('QR Code PIX')}
                        className="h-48 w-48 sm:h-56 sm:w-56"
                      />
                    </div>
                  ) : (
                    <div className="mx-auto flex h-48 w-48 items-center justify-center rounded-2xl border border-white/10 bg-white/[0.03]">
                      <QrCode className="h-16 w-16 text-gray-600" />
                    </div>
                  )}

                  {(paymentResult?.pix_copy_paste ||
                    paymentResult?.pix?.qr_code_text) && (
                    <div className="space-y-2">
                      <p className="text-xs font-semibold uppercase tracking-widest text-gray-500">
                        {t('Pix Copia e Cola')}
                      </p>
                      <div className="flex flex-col gap-2 rounded-xl border border-white/10 bg-white/[0.03] p-3 sm:flex-row sm:items-center">
                        <p className="flex-1 break-all text-left text-xs leading-relaxed text-gray-300 sm:truncate">
                          {paymentResult.pix_copy_paste ||
                            paymentResult.pix?.qr_code_text}
                        </p>
                        <button
                          onClick={copyPixCode}
                          className="shrink-0 rounded-lg bg-brand-600 p-2 text-white transition hover:bg-brand-500"
                          aria-label={t('Copiar código PIX')}
                        >
                          {copied ? (
                            <Check className="h-4 w-4" />
                          ) : (
                            <Copy className="h-4 w-4" />
                          )}
                        </button>
                      </div>
                    </div>
                  )}
                </>
              )}

              {/* Credit Card Pending Flow */}
              {currentCategory === 'card' && (
                <div className="space-y-4">
                  <div className="mx-auto mb-4 flex h-14 w-14 items-center justify-center rounded-2xl border border-brand-500/30 bg-brand-500/10">
                    <CreditCard className="h-7 w-7 text-brand-300" />
                  </div>
                  <h4 className="font-display text-xl font-bold text-white">
                    {t('Pagamento via Cartão')}
                  </h4>
                  <p className="text-sm text-gray-300">
                    {paymentResult?.message ||
                      t('Aguarde a confirmação do seu pagamento.')}
                  </p>
                </div>
              )}

              {/* Mercado Pago Wallet Flow */}
              {currentCategory === 'wallet' && (
                <div className="space-y-4">
                  <div className="mx-auto mb-4 flex h-14 w-14 items-center justify-center rounded-2xl border border-brand-500/30 bg-brand-500/10">
                    <Wallet className="h-7 w-7 text-brand-300" />
                  </div>
                  <h4 className="font-display text-xl font-bold text-white">
                    {t('Pagar com Saldo Mercado Pago')}
                  </h4>
                  <p className="text-sm text-gray-400">
                    {t(
                      'Clique no botão abaixo para concluir o pagamento em sua conta Mercado Pago. Após aprovar, retorne aqui.',
                    )}
                  </p>

                  {(paymentResult?.wallet?.checkout_url ||
                    paymentResult?.payment_url) && (
                    <a
                      href={
                        paymentResult.wallet?.checkout_url ||
                        paymentResult.payment_url
                      }
                      target="_blank"
                      rel="noopener noreferrer"
                      className="btn-primary inline-flex w-full items-center justify-center gap-2 py-3.5 sm:w-auto sm:px-8"
                    >
                      <ExternalLink className="h-4 w-4" />
                      {t('Abrir Mercado Pago')}
                    </a>
                  )}
                </div>
              )}

              {/* PayPal Flow */}
              {currentCategory === 'paypal' && (
                <div className="space-y-4">
                  <div className="mx-auto mb-4 flex h-14 w-14 items-center justify-center rounded-2xl border border-blue-500/30 bg-blue-500/10">
                    <ExternalLink className="h-7 w-7 text-blue-400" />
                  </div>
                  <h4 className="font-display text-xl font-bold text-white">
                    {t('Pagar com PayPal')}
                  </h4>
                  <p className="text-sm text-gray-400">
                    {t(
                      'Clique no botão abaixo para autorizar no PayPal. Depois retorne aqui para confirmar.',
                    )}
                  </p>

                  {paymentResult?.payment_id && (
                    <div className="flex flex-col gap-2 sm:flex-row sm:justify-center">
                      <a
                        href={
                          paymentResult.paypal?.environment === 'sandbox'
                            ? `https://www.sandbox.paypal.com/checkoutnow?token=${paymentResult.paypal?.order_id || paymentResult.payment_id}`
                            : `https://www.paypal.com/checkoutnow?token=${paymentResult.paypal?.order_id || paymentResult.payment_id}`
                        }
                        target="_blank"
                        rel="noopener noreferrer"
                        className="btn-primary inline-flex items-center justify-center gap-2 py-3 px-6"
                      >
                        <ExternalLink className="h-4 w-4" />
                        {t('Abrir PayPal')}
                      </a>

                      <button
                        type="button"
                        onClick={handleCapturePaypal}
                        disabled={capturingPaypal}
                        className="btn-secondary inline-flex items-center justify-center gap-2 py-3 px-6"
                      >
                        {capturingPaypal ? (
                          <Loader2 className="h-4 w-4 animate-spin" />
                        ) : (
                          <Check className="h-4 w-4" />
                        )}
                        {t('Já paguei no PayPal (Confirmar)')}
                      </button>
                    </div>
                  )}
                </div>
              )}

              {/* Ticket / Boleto Flow */}
              {currentCategory === 'ticket' && (
                <div className="space-y-4">
                  <div className="mx-auto mb-4 flex h-14 w-14 items-center justify-center rounded-2xl border border-brand-500/30 bg-brand-500/10">
                    <Receipt className="h-7 w-7 text-brand-300" />
                  </div>
                  <h4 className="font-display text-xl font-bold text-white">
                    {t('Boleto / Ticket de Pagamento')}
                  </h4>

                  {(paymentResult?.ticket?.payment_url ||
                    paymentResult?.payment_url) && (
                    <a
                      href={
                        paymentResult.ticket?.payment_url ||
                        paymentResult.payment_url
                      }
                      target="_blank"
                      rel="noopener noreferrer"
                      className="btn-primary inline-flex w-full items-center justify-center gap-2 py-3.5 sm:w-auto sm:px-8"
                    >
                      <ExternalLink className="h-4 w-4" />
                      {t('Abrir Boleto / Ticket')}
                    </a>
                  )}

                  {paymentResult?.ticket?.barcode && (
                    <div className="space-y-2">
                      <p className="text-xs font-semibold uppercase tracking-widest text-gray-500">
                        {t('Código de Barras / Linha Digitável')}
                      </p>
                      <div className="flex flex-col gap-2 rounded-xl border border-white/10 bg-white/[0.03] p-3 sm:flex-row sm:items-center">
                        <Barcode className="h-5 w-5 text-gray-400 hidden sm:block shrink-0" />
                        <p className="flex-1 break-all text-left font-mono text-xs text-gray-300">
                          {paymentResult.ticket.barcode}
                        </p>
                        <button
                          onClick={copyBarcode}
                          className="shrink-0 rounded-lg bg-brand-600 p-2 text-white transition hover:bg-brand-500"
                          aria-label={t('Copiar código de barras')}
                        >
                          {copied ? (
                            <Check className="h-4 w-4" />
                          ) : (
                            <Copy className="h-4 w-4" />
                          )}
                        </button>
                      </div>
                    </div>
                  )}

                  {paymentResult?.ticket?.expires_at && (
                    <p className="text-xs text-gray-400">
                      {t('Vencimento:')}{' '}
                      <span className="font-semibold text-white">
                        {paymentResult.ticket.expires_at}
                      </span>
                    </p>
                  )}

                  <p className="text-xs text-gray-500">
                    {t(
                      'Realize o pagamento antes do vencimento para liberação automática do seu acesso.',
                    )}
                  </p>
                </div>
              )}

              {/* Universal Polling Status Indicator */}
              <div className="flex items-center justify-center gap-2 text-sm text-gray-400 pt-3">
                <Loader2 className="h-4 w-4 animate-spin text-brand-400" />
                {provisioning
                  ? t('Pagamento confirmado! Criando sua conta...')
                  : paymentStatus === 'pending'
                    ? t('Aguardando confirmação do pagamento...')
                    : t('Verificando pagamento...')}
              </div>

              {pollingError && (
                <p className="text-sm text-red-400">{t(pollingError)}</p>
              )}
            </div>
          )}

          {/* Step 4: Success */}
          {step === 'success' && (
            <div className="space-y-6 text-center">
              <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-full border border-green-500/30 bg-green-500/10">
                <CheckCircle2 className="h-8 w-8 text-green-400" />
              </div>

              <div>
                <h4 className="font-display text-2xl font-bold text-white">
                  {t('Compra Confirmada!')}
                </h4>
                <p className="mt-2 text-sm text-gray-400">
                  {t('Suas credenciais de acesso ao painel estão prontas.')}
                </p>
              </div>

              <div className="space-y-3 rounded-2xl border border-brand-500/20 bg-brand-500/5 p-6 text-left">
                <CredentialRow
                  label={t('Painel')}
                  value={credentials?.panel_url ?? veltrixConfig.panelUrl}
                  isLink
                />
                <CredentialRow
                  label={t('Username')}
                  value={credentials?.username ?? form.resellerUsername}
                  copyable
                />
                <CredentialRow
                  label={t('E-mail')}
                  value={credentials?.email ?? form.resellerEmail}
                />
                <CredentialRow
                  label={t('Senha')}
                  value={credentials?.password ?? form.resellerPassword}
                  copyable
                  secret
                />
              </div>

              <a
                href={credentials?.panel_url ?? veltrixConfig.panelUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="btn-primary w-full py-3.5"
              >
                <Crown className="h-4 w-4" />
                {t('Acessar Painel de Revenda')}
              </a>
            </div>
          )}
        </div>

        {/* Footer actions */}
        {step !== 'success' && step !== 'checkout' && step !== 'pix' && (
          <div className="flex flex-col-reverse gap-2 border-t border-white/[0.06] px-4 py-3.5 sm:flex-row sm:gap-3 sm:px-6 sm:py-4">
            {step === 'payment' && (
              <button
                onClick={() => setStep('credentials')}
                className="btn-secondary flex-1 py-3"
                disabled={submitting}
              >
                <ArrowLeft className="h-4 w-4" />
                {t('Voltar')}
              </button>
            )}

            {step === 'credentials' && (
              <button
                onClick={() => {
                  if (validateCredentials()) goToPaymentStep();
                }}
                className="btn-primary flex-1 py-3"
              >
                {t('Continuar')} <ArrowRight className="h-4 w-4" />
              </button>
            )}

            {step === 'payment' && (
              <button
                onClick={() => {
                  if (validatePayment()) handleCreatePayment();
                }}
                disabled={submitting || loadingMethods}
                className="btn-primary flex-1 py-3 disabled:opacity-50"
              >
                {submitting ? (
                  <>
                    <Loader2 className="h-4 w-4 animate-spin" />
                    {t('Processando...')}
                  </>
                ) : (
                  <>
                    {getSubmitButtonLabel()}{' '}
                    <ArrowRight className="h-4 w-4" />
                  </>
                )}
              </button>
            )}
          </div>
        )}

        {step === 'success' && (
          <div className="border-t border-white/[0.06] px-4 py-3.5 sm:px-6 sm:py-4">
            <button onClick={onClose} className="btn-secondary w-full py-3">
              {t('Fechar')}
            </button>
          </div>
        )}
      </div>
    </div>
  );
}

function Field({
  label,
  icon: Icon,
  children,
}: {
  label: string;
  icon: ComponentType<{ className?: string }>;
  children: React.ReactNode;
}) {
  return (
    <div>
      <label className="mb-1.5 flex items-center gap-1.5 text-sm font-medium text-gray-300">
        <Icon className="h-3.5 w-3.5 text-brand-400" />
        {label}
      </label>
      {children}
    </div>
  );
}

function AvailabilityHint({
  status,
}: {
  status: 'idle' | 'checking' | 'available' | 'taken';
}) {
  if (status === 'idle') return null;

  if (status === 'checking') {
    return (
      <p className="mt-1 flex items-center gap-1 text-xs text-gray-500">
        <Loader2 className="h-3 w-3 animate-spin" /> {t('Verificando...')}
      </p>
    );
  }

  return (
    <p
      className={`mt-1 flex items-center gap-1 text-xs ${status === 'available' ? 'text-green-400' : 'text-red-400'}`}
    >
      {status === 'available' ? (
        <>
          <CheckCircle2 className="h-3 w-3" /> {t('Disponível')}
        </>
      ) : (
        <>{t('Já está em uso')}</>
      )}
    </p>
  );
}

function CredentialRow({
  label,
  value,
  copyable,
  secret,
  isLink,
}: {
  label: string;
  value: string;
  copyable?: boolean;
  secret?: boolean;
  isLink?: boolean;
}) {
  const [copied, setCopied] = useState(false);
  const [revealed, setRevealed] = useState(!secret);

  const handleCopy = async () => {
    await navigator.clipboard.writeText(value);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-col gap-2 rounded-lg border border-white/[0.06] bg-white/[0.03] px-3 py-2.5 sm:flex-row sm:items-center sm:justify-between sm:gap-3 sm:px-4 sm:py-3">
      <div className="min-w-0 flex-1">
        <p className="text-xs text-gray-500">{label}</p>
        {isLink ? (
          <a
            href={value}
            target="_blank"
            rel="noopener noreferrer"
            className="break-all text-sm text-brand-300 hover:underline sm:truncate"
          >
            {value}
          </a>
        ) : (
          <p className="break-all font-mono text-sm text-white sm:truncate">
            {revealed ? value : '••••••••'}
          </p>
        )}
      </div>
      <div className="flex shrink-0 gap-1">
        {secret && (
          <button
            aria-label={revealed ? t('Ocultar senha') : t('Mostrar senha')}
            onClick={() => setRevealed(!revealed)}
            className="rounded-lg p-2 text-gray-400 transition hover:bg-white/5 hover:text-white"
          >
            <Lock className="h-4 w-4" />
          </button>
        )}
        {copyable && (
          <button
            aria-label={t('Copiar credencial')}
            onClick={handleCopy}
            className="rounded-lg p-2 text-gray-400 transition hover:bg-white/5 hover:text-white"
          >
            {copied ? (
              <Check className="h-4 w-4 text-green-400" />
            ) : (
              <Copy className="h-4 w-4" />
            )}
          </button>
        )}
      </div>
    </div>
  );
}
